const NO_SPEECH_TIP: Spoken = {
  text: "何も聞こえませんでした。準備ができたら、もう一度どうぞ。",
  translation: "I didn't hear anything — try again when you're ready.",
};

/** Lines for actions that are NOT generated by the LLM. Returns null if the action uses the LLM reply. */
export function templateFor(action: PolicyAction, ctx: { example?: Spoken; silent?: boolean }): Spoken[] | null {
  switch (action.kind) {
    case "CLARIFY":
      return [ctx.silent ? NO_SPEECH_TIP : action.variant === "rephrase" ? CLARIFY_REPHRASE : CLARIFY_SIMPLIFY];
    case "SUGGEST_AND_MOVE_ON":
      return ctx.example ? [SUGGEST_LEAD, ctx.example] : [SUGGEST_LEAD];
    case "SURPRISE_TOPIC":
      return [SURPRISE];
    case "PROVIDER_ERROR_LINE":
      return [PROVIDER_ERROR];
    case "DECLINE_AND_REDIRECT":
      return [DECLINE];
    case "CLOSE_ONLY":
      return [];
    case "NONE":
    case "PROVIDER_FATAL":
      return [];
    default:
      return null;
  }
}

